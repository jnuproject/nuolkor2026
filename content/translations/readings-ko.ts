export function getLocalizedReadings(
  day: number,
  language: Language,
  english: Reading[],
): Reading[] {
  if (language !== "ko") {
    return english;
  }

  const translations = koreanReadings[day];
  if (!translations) {
    return english;
  }

  return english.map((reading) => {
    const translation = translations[reading.id];
    return translation ? { ...reading, ...translation } : reading;
  });
}
